"""inject.py -- Channel A: prompt injection into the alert.

Five hand-written payloads. They go in the `subject` field, which is exactly the
kind of attacker-controllable string a real SOC pipeline ingests (mail subject,
user-agent, hostname, filename).

Character of this channel: loud, one-shot, inspectable. The payload is sitting
in the ticket where a human can read it. Fix the alert and the attack is gone.
It never affects any other alert.

Deliberately five *different* techniques, so a target that shrugs off one style
does not shrug off all five.
"""

